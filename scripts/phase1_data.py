"""Phase 1: clean, dedup, map labels, write processed splits, dedup report and stats table.

Run from the project root:  python scripts/phase1_data.py
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.data.clean import load_and_clean, n_words  # noqa: E402
from src.data.dedup import deduplicate  # noqa: E402
from src.data.labels import CLASS_NAMES, MAPPINGS, apply_mapping, resplit_depsign, split_dsd  # noqa: E402

OUT = Path("data/processed")
INTERIM = Path("data/interim")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    OUT.mkdir(parents=True, exist_ok=True)
    INTERIM.mkdir(parents=True, exist_ok=True)
    clean_log = {}
    frames = []
    for name in ("depsign", "dsd", "rdc"):
        df = load_and_clean(name, clean_log)
        if name == "dsd":
            df = split_dsd(df)
        df.to_parquet(INTERIM / f"{name}.parquet", index=False)
        frames.append(df)
    all_df = pd.concat(frames, ignore_index=True)
    before = all_df.groupby(["dataset", "split"]).size()

    report = ["# Deduplication report", "",
              "Generated by `scripts/phase1_data.py`.", "", "## Cleaning", ""]
    report += [f"- {k}: {v}" for k, v in clean_log.items()]
    report += ["", "## Duplicates (within and across datasets)", ""]
    deduped = deduplicate(all_df, report)
    after = deduped.groupby(["dataset", "split"]).size()
    deduped = resplit_depsign(deduped)
    final = deduped.groupby(["dataset", "split"]).size()

    report += ["", "## Posts per split, before → after dedup", "",
               "| dataset | split | before | after | removed |", "|---|---|---|---|---|"]
    for (ds, sp), b in before.items():
        a = int(after.get((ds, sp), 0))
        report.append(f"| {ds} | {sp} | {b} | {a} | {b - a} |")
    report += ["", "## Final splits (depsign re-split: train + 80% of dev -> train, 20% of dev -> dev)", ""]
    report += [f"- {ds} {sp}: {n}" for (ds, sp), n in final.items()]
    (OUT / "dedup_report.md").write_text("\n".join(report) + "\n", encoding="utf-8")

    stats = []
    for mapping in MAPPINGS:
        m = apply_mapping(deduped, mapping)
        for split, sub in m.groupby("split"):
            sub.reset_index(drop=True).to_parquet(OUT / f"{mapping}_{split}.parquet", index=False)
            row = {"mapping": mapping, "split": split, "n": len(sub),
                   "mean_words": sub["text"].map(n_words).mean()}
            for c, cname in enumerate(CLASS_NAMES[mapping]):
                row[f"c{c}"] = int((sub["label"] == c).sum())
            stats.append(row)
    stats = pd.DataFrame(stats)
    stats.to_csv(OUT / "dataset_stats.csv", index=False)
    write_latex(stats)
    print("\n".join(report))
    print(stats.to_string(index=False))


def write_latex(stats: pd.DataFrame):
    order = {"train": 0, "dev": 1, "test": 2}
    stats = stats.assign(o=stats["split"].map(order)).sort_values(["mapping", "o"])
    lines = [r"\begin{table}[t]", r"\centering",
             r"\caption{Dataset statistics after cleaning and deduplication. Class 0 = none/minimal,"
             r" 1 = moderate (dsl3: mild+moderate), 2 = severe; rdc is binary.}",
             r"\label{tab:data}", r"\begin{tabular}{llrrrrr}", r"\toprule",
             r"Mapping & Split & $N$ & Class 0 & Class 1 & Class 2 & Mean words \\", r"\midrule"]
    for _, r in stats.iterrows():
        c2 = "--" if pd.isna(r.get("c2")) else f"{int(r['c2']):,}"
        lines.append(f"{r['mapping']} & {r['split']} & {int(r['n']):,} & {int(r['c0']):,} & "
                     f"{int(r['c1']):,} & {c2} & {r['mean_words']:.0f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    Path("results/tables").mkdir(parents=True, exist_ok=True)
    Path("results/tables/table1_dataset_stats.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
